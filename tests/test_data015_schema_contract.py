def test_marker_lookup_does_not_confuse_similar_constant_names() -> None:
    """``SCHEMA_VERSION`` must not resolve to ``MIN_SUPPORTED_SCHEMA_VERSION`` or ``..._V1``.

    Both live in the same files as the real constant, so a sloppy substring match would validate the
    registry against the wrong number and pass while the contract was broken.
    """

    module = _checker()
    source = (
        "pub const MIN_SUPPORTED_SCHEMA_VERSION: i64 = 1;\n"
        "pub const SCHEMA_VERSION: i64 = 4;\n"
        "pub const SCHEMA_VERSION_V1: i64 = 1;\n"
    )
    assert module._declared_constant(source, "SCHEMA_VERSION") == 4
    assert module._declared_constant(source, "MIN_SUPPORTED_SCHEMA_VERSION") == 1
    assert module._declared_constant(source, "SCHEMA_VERSION_V1") == 1
    assert module._declared_constant(source, "NOT_PRESENT") is None
