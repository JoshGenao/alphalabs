def test_mutation_an_unregistered_persisted_writer_is_caught(tmp_path: Path) -> None:
    """The totality clause: a new persisted format cannot slip in unregistered.

    Simulated by removing an entity from the registry — the writer it named is then an unregistered
    persistence surface, which is precisely the state a brand-new unversioned format would create.
    """

    module = _checker()
    source = REGISTRY.read_text(encoding="utf-8")
    start = source.find('    SchemaDescriptor {\n        entity_id: "order-outbox",')
    assert start > 0
    end = source.find("    },\n", start) + len("    },\n")
    entities = module.parse_registry(source[:start] + source[end:])
    with pytest.raises(module.SchemaCheckError) as excinfo:
        module.check_totality(entities)
    assert "crates/atp-execution/src/outbox.rs" in str(excinfo.value)
    assert "neither a registered persisted entity" in str(excinfo.value)


def test_mutation_a_stale_allow_list_entry_is_caught(monkeypatch: pytest.MonkeyPatch) -> None:
    """An exemption for a file that persists nothing silently widens the allow-list."""

    module = _checker()
