"""L3 contract test for SRS-DATA-015 (schema evolution for stored data entities).

Two layers of evidence:

* :func:`test_check_script_passes` runs ``tools/data015_schema_check.py`` against the real tree, so
  the positive-evidence path stays under CI coverage.
* the **mutation** tests feed the checker deliberately-broken registries and confirm each one FAILS.
  A gate that cannot fail is not a gate: without these, the check could silently degrade to printing
  PASS unconditionally and nothing would notice.
"""

from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
CHECK = ROOT / "tools" / "data015_schema_check.py"
REGISTRY = ROOT / "crates" / "atp-data" / "src" / "schema_registry.rs"
CORPUS = ROOT / "tests" / "fixtures" / "schema_evolution"

pytestmark = [pytest.mark.contract]

_CONTRACT = json.loads((ROOT / "architecture" / "runtime_services.json").read_text())[
    "schema_evolution_contract"
]


def _checker():
    """Import the check script as a module so the mutation tests can call its parts directly."""

    spec = importlib.util.spec_from_file_location("data015_schema_check", CHECK)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module  # dataclasses needs the module registered
    spec.loader.exec_module(module)
    return module


# --------------------------------------------------------------------------- #
# Positive evidence
# --------------------------------------------------------------------------- #


def test_check_script_passes() -> None:
    result = subprocess.run(
        [sys.executable, str(CHECK)], capture_output=True, text=True, check=False
    )
    assert result.returncode == 0, result.stderr
    assert "SRS-DATA-015 SCHEMA-EVOLUTION PASS" in result.stdout


def test_registry_parses_every_declared_entity() -> None:
    module = _checker()
    entities = module.parse_registry(REGISTRY.read_text(encoding="utf-8"))
    assert len(entities) == _CONTRACT["entity_count"]
    assert len({e.entity_id for e in entities}) == len(entities)


def test_contract_block_names_artifacts_that_exist() -> None:
    for key in ("registry_module", "check_script", "cli", "golden_corpus"):
        assert (ROOT / _CONTRACT[key]).exists(), f"{key} points at a missing path"


def test_retrofitted_entities_match_the_registry() -> None:
    module = _checker()
    entities = module.parse_registry(REGISTRY.read_text(encoding="utf-8"))
    retrofitted = {e.entity_id for e in entities if e.legacy_unversioned}
    assert retrofitted == set(_CONTRACT["retrofitted_entities"])


def test_every_retrofitted_entity_has_a_frozen_fixture() -> None:
    module = _checker()
    entities = module.parse_registry(REGISTRY.read_text(encoding="utf-8"))
    for entity in entities:
        if not entity.legacy_unversioned:
            continue
        fixture = module.CORPUS_FIXTURES[entity.entity_id]
        assert (CORPUS / fixture).is_file(), f"{entity.entity_id}: missing {fixture}"


def test_no_legacy_fixture_carries_a_version_key() -> None:
    """The corpus must actually be *legacy*.

    If a "legacy" fixture were regenerated by the current writer it would carry a version key, and
    every no-bulk-migration assertion over it would silently become a round-trip test.
    """

    module = _checker()
    for fixture in module.CORPUS_FIXTURES.values():
        text = (CORPUS / fixture).read_text(encoding="utf-8")
        assert "schema_version" not in text, f"{fixture} is not a pre-versioning payload"
        assert not text.startswith("v1\t"), f"{fixture} is not a pre-versioning payload"


# --------------------------------------------------------------------------- #
# Mutation guards — each broken registry MUST fail the checker
# --------------------------------------------------------------------------- #


def _expect_failure(module, source: str, fragment: str) -> None:
    with pytest.raises(module.SchemaCheckError) as excinfo:
        entities = module.parse_registry(source)
        module.check_registry_invariants(entities)
        module.check_writer_binding(entities)
    assert fragment in str(excinfo.value), f"wrong failure: {excinfo.value}"


def test_mutation_a_dropped_registry_entry_is_caught() -> None:
    """The parse-hole guard: a silently-skipped entry must be a hard failure."""

    module = _checker()
    source = REGISTRY.read_text(encoding="utf-8")
    # Break the LAST entry's terminator, the exact shape that dropped an entry during development.
    broken = source.replace('entity_id: "config-vault-envelope",', 'entity_id_typo: "x",')
    with pytest.raises(module.SchemaCheckError) as excinfo:
        module.parse_registry(broken)
    assert "dropped an entry" in str(excinfo.value) or "missing field" in str(excinfo.value)


def test_mutation_a_wrong_current_version_is_caught() -> None:
    """The registry may not claim a version the writer does not define."""

    module = _checker()
    source = REGISTRY.read_text(encoding="utf-8").replace(
        'entity_id: "market-data-store",\n        owner_srs: "SRS-DATA-016",',
        'entity_id: "market-data-store",\n        owner_srs: "SRS-DATA-016",',
    )
    source = source.replace("current_version: 4,", "current_version: 9,", 1)
    _expect_failure(module, source, "defines SCHEMA_VERSION=4")


def test_mutation_a_bogus_marker_is_caught() -> None:
    """A marker the writer does not contain means the version never reaches the bytes."""

    module = _checker()
    source = REGISTRY.read_text(encoding="utf-8").replace(
        'marker: "ACCESS_JOURNAL_SCHEMA_VERSION",', 'marker: "NOT_A_REAL_CONSTANT",', 1
    )
    _expect_failure(module, source, "does not mention its version marker")


